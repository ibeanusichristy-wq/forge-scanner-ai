CREATE TABLE IF NOT EXISTS public.trade_signals (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  pair TEXT NOT NULL,
  direction TEXT NOT NULL CHECK (direction IN ('BUY','SELL','WAIT')),
  entry_price NUMERIC(20,10) NOT NULL,
  stop_loss NUMERIC(20,10) NOT NULL,
  take_profit NUMERIC(20,10) NOT NULL,
  confidence INTEGER NOT NULL CHECK (confidence BETWEEN 1 AND 100),
  analysis_note TEXT,
  status TEXT NOT NULL DEFAULT 'pending' CHECK (status IN ('pending','approved','rejected')),
  created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  approved_at TIMESTAMPTZ
);
